/**
 * Shared organization visual utilities used by multiple components.
 * Mirrors the workspace-utils.ts pattern.
 */

export function getOrganizationInitials(name: string): string {
  return name
    .split(' ')
    .map((n) => n[0])
    .join('')
    .toUpperCase()
    .slice(0, 2);
}

export const ORGANIZATION_AVATAR_COLORS = [
  'from-blue-500 to-indigo-600',
  'from-purple-500 to-violet-600',
  'from-emerald-500 to-teal-600',
  'from-amber-500 to-orange-600',
  'from-rose-500 to-pink-600',
  'from-cyan-500 to-blue-600',
];

export function getOrganizationAvatarGradient(name: string): string {
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = name.charCodeAt(i) + ((hash << 5) - hash);
  }
  return ORGANIZATION_AVATAR_COLORS[Math.abs(hash) % ORGANIZATION_AVATAR_COLORS.length];
}
